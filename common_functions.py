###############################################################
# Header
###############################################################

def header(message):

    print("\n")
    print("=" * 80)
    print(message)
    print("=" * 80)


###############################################################
# Footer
###############################################################
 
def footer():

    print("=" * 80)
    print("PROCESS COMPLETED")
    print("=" * 80)


###############################################################
# Display Data
###############################################################

def display_data(df, rows=5):

    print("\nDisplaying Sample Data")

    df.show(rows, truncate=False)


###############################################################
# Row Count
###############################################################

def display_row_count(df):

    print("\nRow Count :", df.count())


###############################################################
# Column Count
###############################################################

def display_column_count(df):

    print("\nColumn Count :", len(df.columns))


###############################################################
# Column Names
###############################################################

def display_columns(df):

    print("\nColumns")

    print(df.columns)


###############################################################
# Schema
###############################################################

def display_schema(df):

    print("\nSchema")

    df.printSchema()


